/**
 * Detects the active language from localStorage, then the browser, then English.
 */
function detectLanguage() {
  const stored  = localStorage.getItem('pgpt-lang');
  const browser = (navigator.language || '').slice(0, 2).toLowerCase();
  if (stored  && SUPPORTED_LANGS.includes(stored))  return stored;
  if (browser && SUPPORTED_LANGS.includes(browser)) return browser;
  return DEFAULT_LANG;
}

/**
 * Applies translations to every [data-i18n] and [data-i18n-html] element,
 * updates <html lang>, and highlights the active language button.
 */
function applyTranslations(lang) {
  const strings = T[lang] || T[DEFAULT_LANG];
  const year    = new Date().getFullYear();
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (strings[key]) el.textContent = strings[key].replace('{year}', year);
  });
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const key = el.getAttribute('data-i18n-html');
    if (strings[key]) el.innerHTML = strings[key].replace('{year}', year);
  });
  document.documentElement.lang = lang;
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === lang);
  });
}

/** Sets, persists and applies a language. */
function setLanguage(lang) {
  if (!SUPPORTED_LANGS.includes(lang)) lang = DEFAULT_LANG;
  localStorage.setItem('pgpt-lang', lang);
  applyTranslations(lang);
}

/* ─── INIT ─────────────────────────────────────────────────────────────────── */
document.addEventListener('DOMContentLoaded', () => {
  // Wire up language switcher buttons
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.addEventListener('click', () => setLanguage(btn.dataset.lang));
  });

  // Apply the detected language on first load
  applyTranslations(detectLanguage());
});
